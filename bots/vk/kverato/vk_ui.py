def resolve_vk_input(text: str) -> tuple[str, str | None]:
    text=text.strip()
    known=LABELS.get(text)
    if known is not None:
        return known
    prefix=text[:1] if text[:1] in ('!', '/', '.') else ''
    cmd=text[len(prefix):].strip().lower()
    if cmd in _RANK_PHRASES:
        return prefix+_RANK_PHRASES[cmd], None
    return text, None


def keyboard_json(page: str = 'main') -> str:
    rows = KEYBOARDS.get(page, MAIN)
    return json.dumps({
        'one_time': False,
        'inline': False,
        'buttons': [[{'action': {'type': 'text', 'label': label}, 'color': color}
                     for label, color in row] for row in rows],
    }, ensure_ascii=False, separators=(',', ':'))

